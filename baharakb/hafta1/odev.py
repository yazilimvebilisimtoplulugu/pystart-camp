kisi1 = input("1. kisinin hobileri: ")
kisi2 = input("2. kisinin hobileri: ")
kume1 = set(kisi1.split(","))
kume2 = set(kisi2.split(","))
print("Ortak hobiler:", sorted(kume1 & kume2))
print("Yalnizca birincide olanlar:", sorted(kume1 - kume2))
print("Yalnizca ikincide olanlar:", sorted(kume2 - kume1))
print("Tum hobiler:", sorted(kume1 | kume2))
print("Ortak hobiniz var mi?:", len(kume1 & kume2) > 0)
print("Hobi sayilariniz esit mi?:", len(kume1) == len(kume2))
print("Ikiniz de en az 3 hobi yazdiniz mi?:", len(kume1) >= 3 and len(kume2) >= 3)
print("'satranç' ikinizden birinin hobisi mi?:", "satranç" in (kume1 | kume2))
