girilenNot=input("3 Not Giriniz: ")
parcalar=girilenNot.split()
notlar=[int(parcalar[0]), int(parcalar[1]),int(parcalar[2])]
yeniNot=int(input("Bir Not Giriniz: "))
notlar.append(yeniNot)
notlar.sort()
print(f"notlar:{notlar}")
en_dusuk=min(notlar)
en_yuksek=max(notlar)
ortalama=sum(notlar)/len(notlar)
print(f"En düşük: {en_dusuk}, En yüksek: {en_yuksek}")
print(f"Ortalama: {ortalama:.2f}")
notlar.pop(0)
yeni_ortalama = sum(notlar) / len(notlar)
print(f"En düşük not çıkarıldı: {notlar}")
print(f"Yeni ortalama: {yeni_ortalama:.2f}")

